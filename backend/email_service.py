"""Build the HTML report and send it with SendGrid."""
import asyncio
import html
from datetime import datetime, timezone

from sendgrid import SendGridAPIClient
from sendgrid.helpers.mail import Mail

from backend.config import get_settings
from backend.schemas import StartupProfile


def _cell(value: str, url: str | None) -> str:
    v = html.escape(value or "Not found")
    if v.lower() == "not found":
        return '<span style="color:#9aa0a6">Not found</span>'
    if url and url.startswith("http"):
        return f'{v} <a href="{html.escape(url)}" style="color:#1a73e8;font-size:11px">[src]</a>'
    return v


def build_report_html(criteria: str, attributes: list[str], profiles: list[StartupProfile]) -> str:
    th = "padding:8px 10px;border:1px solid #dadce0;background:#f1f3f4;text-align:left;font-size:13px"
    td = "padding:8px 10px;border:1px solid #dadce0;vertical-align:top;font-size:13px"

    header = "".join(f'<th style="{th}">{html.escape(a)}</th>' for a in attributes)
    rows = []
    for p in profiles:
        cells = "".join(f'<td style="{td}">{_cell(a.value, a.source_url)}</td>' for a in p.attributes)
        rows.append(f"<tr>{cells}</tr>")

    summaries = "".join(
        f'<li style="margin-bottom:10px"><b>{html.escape(p.company_name)}</b> — {html.escape(p.summary)}</li>'
        for p in profiles
    )
    date = datetime.now(timezone.utc).strftime("%d %b %Y")

    return f"""\
<div style="font-family:Arial,Helvetica,sans-serif;color:#202124;max-width:1100px">
  <h2 style="margin-bottom:4px">Investment Sourcing Report</h2>
  <div style="color:#5f6368;font-size:13px">{date} · {len(profiles)} startups found</div>
  <h3 style="margin-top:20px">Search criteria</h3>
  <p style="background:#f8f9fa;padding:10px;border-left:3px solid #1a73e8;white-space:pre-wrap">{html.escape(criteria)}</p>
  <h3>Startups</h3>
  <div style="overflow-x:auto">
  <table style="border-collapse:collapse;width:100%">
    <thead><tr>{header}</tr></thead>
    <tbody>{''.join(rows)}</tbody>
  </table>
  </div>
  <h3>Analyst summaries</h3>
  <ul style="padding-left:18px">{summaries}</ul>
  <p style="color:#9aa0a6;font-size:11px">Generated by the Investments Sourcing Agent (LangChain + Linkup).
  Verify all data before making investment decisions.</p>
</div>"""


def _send_sync(to_email: str, subject: str, html_content: str) -> int:
    s = get_settings()
    if not s.sendgrid_api_key or not s.sendgrid_from_email:
        raise RuntimeError("SENDGRID_API_KEY / SENDGRID_FROM_EMAIL are not set")
    msg = Mail(from_email=s.sendgrid_from_email, to_emails=to_email,
               subject=subject, html_content=html_content)
    resp = SendGridAPIClient(s.sendgrid_api_key).send(msg)
    return resp.status_code


async def send_report(to_email: str, subject: str, html_content: str) -> int:
    return await asyncio.to_thread(_send_sync, to_email, subject, html_content)
